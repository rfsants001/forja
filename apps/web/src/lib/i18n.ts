// Função de tradução
// ---------------------------------------------------------------------------

/**
 * Resolve uma chave no idioma pedido.
 * Fallback: se a chave não existir em EN, usa PT.
 * Interpolação: `{0}`, `{1}`, ... são substituídos pelos valores de `params`.
 */
export function t(key: string, lang: Lang, params?: (string | number)[]): string {
  const dict = messages[lang] ?? messages['pt'];
  const fallback = messages['pt'];
  const expansion: Record<Lang, Record<string, string>> = expansionMessages;
  let str = dict[key] ?? expansion[lang]?.[key] ?? fallback[key] ?? expansion.pt[key] ?? key;

  if (params !== undefined && params.length > 0) {
    params.forEach((val, i) => {
      str = str.replaceAll(`{${i}}`, String(val));
    });
  }

  return str;
}

// ---------------------------------------------------------------------------
// Hook reativo
// ---------------------------------------------------------------------------

/**
 * Hook que lê `Settings.lang` via useLiveQuery e devolve uma função
 * `t(key, params?)` já amarrada no idioma atual. Padrão: 'pt'.
 */
export function useT(): (key: string, params?: (string | number)[]) => string {
  const settings = useLiveQuery(() => db.settings.get('app'), []);
  const lang: Lang = (settings?.lang as Lang | undefined) ?? 'pt';

  return useCallback((key: string, params?: (string | number)[]) => t(key, lang, params), [lang]);
}
